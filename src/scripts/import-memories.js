async function importMemories() {
  console.log(`开始导入 ${memories.length} 条记忆...`);
  
  for (let i = 0; i < memories.length; i++) {
    try {
      const response = await axios.post(API_URL, {
        content: memories[i]
      });
      console.log(`[${i + 1}/${memories.length}] 成功: ${memories[i].substring(0, 30)}...`);
    } catch (err) {
      console.error(`[${i + 1}/${memories.length}] 失败: ${err.message}`);
    }
    
    // 避免请求过快
    await new Promise(resolve => setTimeout(resolve, 500));
  }
  
  console.log('导入完成！');
}

